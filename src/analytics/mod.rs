/// Maximum number of events sent in a single flush, bounding worst-case time.
const MAX_FLUSH_PER_RUN: usize = 50;

/// Drop events that have failed to send this many times.
const MAX_SEND_ATTEMPTS: i64 = 6;

/// Discard queued events older than this on flush.
const RETENTION_MS: i64 = 30 * 24 * 60 * 60 * 1000;

/// Overall flush budget so analytics never noticeably delays process exit. Set
/// to one per-request timeout ([`tracks::REQUEST_TIMEOUT`]) plus a small margin
/// so a stalled request hits its own timeout — and gets its attempt counted or
/// dropped inside `drain_queue` — before the outer [`tokio::time::timeout`]
/// cancels the drain mid-row (which would otherwise let the same row retry
/// forever). The durable queue drains anything left over on the next run.
const FLUSH_BUDGET: Duration = tracks::REQUEST_TIMEOUT.saturating_add(Duration::from_millis(500));

/// Process-global analytics state, initialised once per invocation by
/// [`init`]. Absent (or `enabled == false`) means every entry point no-ops.
struct State {
    enabled: bool,
    app_version: &'static str,
    os: String,
    identity: Mutex<Identity>,
}

static STATE: OnceLock<State> = OnceLock::new();

/// Initialise analytics for this invocation: resolve the install-level
/// anonymous id (generating and persisting one on first run), derive identity
/// from any stored session, and compute the opt-out gate.
pub fn init(config_dir: &Path, config: &mut AppConfig, store: &Store, base_url: &str) {
    let anon_id = match config.analytics.anonymous_id.as_deref() {
        // Accept only IDs generated by this client. A hand-edited config value
        // must not become a free-form Tracks identity or alias property.
        Some(existing) if identity::is_valid_anonymous_id(existing.trim()) => {
            existing.trim().to_owned()
        }
        _ => {
            let generated = identity::new_anonymous_id();
            config.analytics.anonymous_id = Some(generated.clone());
            // Best-effort: a failure to persist just means we regenerate next
            // run. Never surface analytics setup errors to the user.
            let _ = config.save(config_dir);
            generated
        }
    };

    let session = store.get_auth_session_for_base_url(base_url).ok().flatten();
    let (signed_in, subscription_level) = match session {
        Some(session) => {
            let user = serde_json::from_str::<Value>(&session.user_json).unwrap_or(Value::Null);
            (
                // We record only whether a session exists, never the user id.
                identity::user_id_from_user_value(&user).is_some(),
                identity::subscription_level_from_user_value(&user),
            )
        }
        None => (false, None),
    };

    let enabled = tracks_enabled_for_api(base_url)
        && crate::telemetry::is_enabled()
        && server_analytics_enabled(store);

    let state = State {
        enabled,
        app_version: env!("CARGO_PKG_VERSION"),
        os: format!("{} {}", std::env::consts::OS, std::env::consts::ARCH),
        identity: Mutex::new(Identity {
            signed_in,
            anon_id,
            subscription_level,
        }),
    };
    // Ignore a double-init (only happens in tests that call run() twice in the
    // same process); the first state wins.
    let _ = STATE.set(state);
}

/// Enqueue a tracked event. Cheap and infallible from the caller's view.
pub fn track(store: &Store, event: Event, props: &[(&str, Value)]) {
    let Some(state) = enabled_state() else {
        return;
    };
    let full_name = event.full_name();
    if !tracks::is_valid_name(&full_name) {
        return;
    }
    let custom = filter_custom_properties(event, props.iter().map(|(key, value)| (*key, value)));
    enqueue_params(store, state, &full_name, custom);
}

fn filter_custom_properties<'a>(
    event: Event,
    props: impl IntoIterator<Item = (&'a str, &'a Value)>,
) -> Map<String, Value> {
    let mut custom = Map::new();
    let mut rejected = 0usize;
    for (key, value) in props {
        if custom_property_allowed(event, key, value) {
            custom.insert(key.to_owned(), value.clone());
        } else {
            rejected += 1;
        }
    }
    if rejected > 0 {
        warn_rejected_properties(event, rejected);
    }
    custom
}

fn custom_property_allowed(event: Event, key: &str, value: &Value) -> bool {
    match (event, key) {
        (Event::CommandRun, "command") => value.as_str().is_some_and(is_known_command),
        (Event::CommandRun, "subcommand") => value.as_str().is_some_and(is_known_subcommand),
        (Event::CommandRun, "outcome") => value
            .as_str()
            .is_some_and(|value| matches!(value, "success" | "user_error" | "error")),
        (Event::CommandRun, "duration_ms") => value.as_i64().is_some_and(|value| value >= 0),
        (Event::JournalCreate, "shared" | "encrypted")
        | (Event::EntryCreate | Event::EntryEditFinish, "synced") => value.is_boolean(),
        _ => false,
    }
}


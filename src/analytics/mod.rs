//! Product analytics for the Day One CLI, reporting into Automattic Tracks.
//!
//! Design (see also the project plan):
//!
//! - **Transport** is the Tracks REST endpoint (`src/analytics/tracks.rs`),
//!   `POST /rest/v1.1/tracks/record`, which the whole local queue is drained
//!   into as a single batched request per flush. Events are prefixed
//!   `dayone_cli_`.
//! - **Durability** comes from a local SQLite queue: handlers [`track`] events
//!   (a cheap insert), and a best-effort [`flush`] drains the queue at the end
//!   of each invocation. The flush is awaited but tightly time-bounded (see
//!   [`FLUSH_BUDGET`]), so analytics adds at most one request timeout to a
//!   command and never fails one; whatever does not drain in that window is
//!   retried on the next invocation.
//! - **Identity** is always the install-level anonymous id (`_ut = anon`),
//!   before *and* after sign-in. CLI telemetry is deliberately never tied to
//!   the Day One account: the user id is not used as the Tracks identity and no
//!   `_aliasUser` event is emitted. Sign-in state is surfaced only as the
//!   `is_signed_in` event property (see [`identify_on_login`]).
//! - **Scope and opt-out** limit real Tracks delivery to the production Day One
//!   API. `DAYONE_TRACKS_ENDPOINT` explicitly enables local or test delivery for
//!   other API environments. Runtime opt-outs (`DO_NOT_TRACK`,
//!   `DAYONE_TELEMETRY`) and the server-side `track_usage_statistics` account
//!   setting still apply.
//!
//! All public entry points are no-ops when analytics is disabled or the
//! profile database is missing, so callers never need to branch on state.

